test('V2 reduced-motion preference stops decorative motion and keeps keyboard skip navigation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await setupFamily(page)
  await page.goto('/bedtime/today')
  await expect(page.locator('.calm-card')).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter((a) => a.playState === 'running').length)).toBe(0)
  await page.keyboard.press('Tab')
  const skip = page.getByRole('link', { name: '跳到当前内容' })
  await expect(skip).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#child-content')).toBeFocused()
  await expectComfortable(page)
})
